#!/usr/bin/env python3
"""Render the generated endpoint reference from a backend skill manifest."""
from __future__ import annotations
import argparse, hashlib, json
from pathlib import Path
from typing import Any

def render(manifest: dict[str, Any]) -> str:
    raw = json.dumps(manifest, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
    digest = manifest.get("content_hash") or hashlib.sha256(raw).hexdigest()
    lines = ["<!-- DO NOT EDIT: generated by tools/gen_reference.py -->",
        f"<!-- manifest-version: {manifest.get('version', 'unknown')} -->",
        f"<!-- manifest-sha256: {digest} -->", "", "# API 端点事实表", "",
        f"品牌：{manifest.get('brand', 'AIComing')}  ", f"API：`{manifest.get('base_url', '')}`  ",
        f"控制台：{manifest.get('console_url', '')}", "", "| 方法 | 路径 | 用途 | 计费 | 异步 |",
        "|---|---|---|---|---|"]
    for ep in manifest.get("endpoints", []):
        lines.append("| {method} | `{path}` | {summary} | {billing} | {async_} |".format(
            method=ep.get("method", ""), path=ep.get("path", ""),
            summary=str(ep.get("summary", "")).replace("|", "\\|"),
            billing=ep.get("billing", "unknown"), async_="是" if ep.get("async") else "否"))
    lines += ["", "> 素材库等能力以当前站点 manifest 的 `capabilities` 为准；关闭时不要向用户展示对应入口。", ""]
    return "\n".join(lines)

def main() -> int:
    parser = argparse.ArgumentParser(); parser.add_argument("manifest", type=Path)
    parser.add_argument("--output", type=Path, default=Path("aicoming/references/endpoints.generated.md")); args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text("utf-8")); args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(manifest), "utf-8"); return 0

if __name__ == "__main__": raise SystemExit(main())

